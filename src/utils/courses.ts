export type CourseKey = 'probability' | 'ml' | 'deep-learning' | 'bayesian-methods' | 'generative-models' | 'nlp' | 'acos' | 'agents' | 'math' | 'python';

export type CourseTopic = string | { title: string; note: string; anchor?: string };

export interface CourseSection {
  title: string;
  /** One line on what the section answers. */
  summary?: string;
  /** What a reader can do after the section. */
  outcome?: string;
  topics: CourseTopic[];
}

/** A stage of the course storyline: its label and the section (or note) it opens. */
export interface ProgressionStage { label: string; section?: string; note?: string }

export interface Course {
  title: string;
  /** Courses to take before this one; the /notes page draws the courses as a graph from these edges. */
  requires: CourseKey[];
  shortTitle: string;
  description: string;
  /** What to know before starting, and how the course is meant to be read. */
  entry: string;
  /** Links from the course page to the notes that lay out the course as a whole (its map, its closing summary). */
  guide: { label: string; note: string; anchor: string }[];
  /** Notes (or `note#anchor` sections) that branch off the main route: the rest of the course reads without them. */
  extensions?: string[];
  /** The course storyline as a sequence of stages; each stage links to a section of the course page (or to a note). */
  progression: ProgressionStage[];
  sections: CourseSection[];
  /** Russian texts for the course page. `labels` maps English section titles, summaries and topic titles to Russian. */
  ru: {
    title: string;
    shortTitle: string;
    description: string;
    entry: string;
    /** Russian stage labels, in the order of `progression`. */
    progression?: string[];
    labels: Record<string, string>;
  };
}

// A string is a planned topic. Published topics explicitly name their note and,
// where useful, a section: article titles are not a reliable coverage map.
function noteTopic(title: string, note: string, anchor?: string): CourseTopic {
  return { title, note, anchor };
}

